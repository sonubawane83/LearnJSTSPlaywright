
// BigInt Literals : Are used to store Large whole numbers that are bigger than the safe 
// limit of the number Type

let bigger1 = 1234567890123456789012345678901234567890n;
console.log(typeof bigger1, bigger1); // typeof is bigint because it is a BigInt literal

let bigger2 = 100n;
console.log(typeof bigger2, bigger2); // typeof is bigint because it is a BigInt literal

