
//Null : null means intentionally empty or no value.
let empty = null;
console.log(typeof empty, empty); // typeof is object because null is a type of object in JavaScript

// Undefined : undefined means a variable has been declared but has not yet been assigned a value.
let notAssigned;
console.log(typeof notAssigned, notAssigned); // typeof is undefined because variable has not been 
                                             // assigned a value yet.    




