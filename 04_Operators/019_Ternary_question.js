//in automation we use Ternary operators you check the condition

//Ternary operators condition is either true or false 
// Syntax -> condition? if(true) do this: if false(do this)
let age = 18;
let result = age >= 18 ? "You are eligible to vote" : "You are not eligible to vote";
console.log(result); // You are eligible to vote


